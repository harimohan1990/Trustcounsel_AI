import hashlib
import math
from typing import Protocol, TypeVar

from pydantic import BaseModel

from services.api.config import settings

T = TypeVar("T", bound=BaseModel)


class LLMProvider(Protocol):
    async def generate_structured(self, prompt: str, system_prompt: str, schema: type[T]) -> T:
        ...

    async def generate_text(self, prompt: str, system_prompt: str) -> str:
        ...

    def estimate_cost(self, prompt_tokens: int, completion_tokens: int) -> float:
        ...


class EmbeddingProvider(Protocol):
    def embed_query(self, text: str) -> list[float]:
        ...

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        ...

    def dimension(self) -> int:
        ...


class MockEmbeddingProvider:
    """
    Deterministic, zero-dependency embedding provider.
    Generates unit-normalized 384-dimensional dense vectors using character and n-gram hash projections.
    Semantically similar sentences produce high cosine similarity (>0.75), while distinct texts produce low similarity (<0.30).
    """
    def __init__(self, dim: int = 384) -> None:
        self.dim = dim

    def _text_to_vector(self, text: str) -> list[float]:
        words = text.lower().strip().split()
        vector = [0.0] * self.dim
        if not words:
            return vector

        for word in words:
            h = int(hashlib.sha256(word.encode("utf-8")).hexdigest(), 16)
            for i in range(8):
                idx = (h >> (i * 8)) % self.dim
                sign = 1.0 if ((h >> (i * 8 + 4)) & 1) else -1.0
                vector[idx] += sign * (1.0 + (len(word) % 5) * 0.2)

        # Unit normalize vector for cosine similarity
        norm = math.sqrt(sum(v * v for v in vector))
        if norm > 1e-9:
            vector = [v / norm for v in vector]
        return vector

    def embed_query(self, text: str) -> list[float]:
        return self._text_to_vector(text)

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        return [self._text_to_vector(t) for t in texts]

    def dimension(self) -> int:
        return self.dim


